# Cookbook:: redis
# Provider:: config

include Redis::Helper

action :add do
  begin
    user = new_resource.user
    group = new_resource.group
    cdomain = new_resource.cdomain
    redis_dir = new_resource.redis_dir
    data_dir = new_resource.data_dir
    log_file = new_resource.log_file
    pid_file = new_resource.pid_file
    redis_hosts = new_resource.redis_hosts
    sentinel_data_dir = new_resource.sentinel_data_dir
    sentinel_log_file = new_resource.sentinel_log_file
    sentinel_pid_file = new_resource.sentinel_pid_file
    cluster_info = get_cluster_info(redis_hosts)

    execute 'reset redis module' do
      command 'dnf module reset -y redis'
      only_if 'dnf module list --enabled | grep -q "^redis"'
    end

    execute 'disable redis module' do
      command 'dnf module disable -y redis'
      not_if 'dnf module list --disabled | grep -q "^redis"'
    end

    execute 'lock redis version' do
      command "dnf versionlock add --raw 'redis-6.*'"
      not_if 'dnf versionlock list | grep redis'
    end

    dnf_package 'redis' do
      action :upgrade
    end

    execute 'create_user' do
      command "/usr/sbin/useradd -r #{user} -s /sbin/nologin"
      ignore_failure true
      not_if "getent passwd #{user}"
    end

    # redis may not write its config dir: a CONFIG REWRITE (Sentinel failover) would put the password into redis.conf
    # same modes as the tmpfiles override: the package resets /etc/redis at every boot
    conf_owner = 'root'
    conf_mode = '0640'
    file '/etc/tmpfiles.d/redis.conf' do
      content "# Generated by chef (cookbook-redis): redis may read its config, not rewrite it (passwords from /run)\nZ #{redis_dir} ~0750 root #{group} -\n"
      mode '0644'
      action :create
      notifies :run, 'execute[tmpfiles-redis-conf]', :immediately
    end

    execute 'tmpfiles-redis-conf' do
      command '/usr/bin/systemd-tmpfiles --create /etc/tmpfiles.d/redis.conf'
      action :nothing
    end

    directory redis_dir do
      owner conf_owner
      group group
      mode '0750'
    end

    directory data_dir do
      owner user
      group group
      mode '0755'
    end

    openbao_secret_file 'redis-auth' do
      source 'redis-auth.conf.ctmpl.erb'
      cookbook 'redis'
      destination '/run/rb-secrets/redis/auth.conf'
      selinux_type 'redis_var_run_t' # redis runs confined (redis_t)
      owner 'root'
      group group
      mode '0640'
      unit 'redis'
      action :add
    end

    template "#{redis_dir}/redis-base.conf" do
      source 'redis-base.conf.erb'
      owner conf_owner
      group group
      mode conf_mode
      cookbook 'redis'
      variables(
        port: node['redis']['port'],
        cdomain: cdomain,
        data_dir: data_dir,
        log_file: log_file,
        pid_file: pid_file,
        is_cluster: cluster_info[:is_cluster],
        master_host: cluster_info[:master_host],
        is_master_here: cluster_info[:is_master_here]
      )
      notifies :restart, 'service[redis]', :delayed
    end

    file "#{redis_dir}/redis.conf" do
      action :delete
      only_if do
        ::File.exist?("#{redis_dir}/redis.conf") &&
          !::File.read("#{redis_dir}/redis.conf").include?("include #{redis_dir}/redis-base.conf")
      end
    end

    file "#{redis_dir}/redis.conf" do
      content "include #{redis_dir}/redis-base.conf\n"
      owner conf_owner
      group group
      mode conf_mode
      action :create# also undo a leaked rewrite
    end

    service 'redis' do
      service_name 'redis'
      ignore_failure true
      supports status: true, restart: true, enable: true
      action [:start, :enable]
    end

    if redis_hosts.length > 1
      directory sentinel_data_dir do
        owner user
        group group
        mode '0755'
      end

      template "#{redis_dir}/sentinel-base.conf" do
        source 'sentinel-base.conf.erb'
        owner conf_owner
        group group
        mode conf_mode
        cookbook 'redis'
        variables(
          data_dir: sentinel_data_dir,
          log_file: sentinel_log_file,
          pid_file: sentinel_pid_file,
          sentinel_port: node['redis']['sentinel_port']
        )
        notifies :restart, 'service[redis-sentinel]', :delayed
      end

      file "#{redis_dir}/sentinel.conf" do
        action :delete
        only_if do
          ::File.exist?("#{redis_dir}/sentinel.conf") &&
            !::File.read("#{redis_dir}/sentinel.conf").include?("include #{redis_dir}/sentinel-base.conf")
        end
      end

      file "#{redis_dir}/sentinel.conf" do
        content <<~CONF
          include #{redis_dir}/sentinel-base.conf
          sentinel monitor mymaster #{cluster_info[:master_ip]} #{node['redis']['port']} 2
        CONF
        owner conf_owner
        group group
        mode conf_mode
        action :create_if_missing
      end

      # an install from before OpenBao wrote the password here
      execute 'remove-sentinel-auth-pass' do
        command "sed -i '/^sentinel auth-pass /d' #{redis_dir}/sentinel.conf"
        only_if { ::File.exist?("#{redis_dir}/sentinel.conf") && ::File.read("#{redis_dir}/sentinel.conf").match?(/^sentinel auth-pass /) }
      end

      # Sentinel rewrites its config with auth-pass: it runs on a copy in /run seeded from /etc/redis/sentinel.conf
      sentinel_run = '/run/redis-sentinel'
      openbao_secret_file 'redis-sentinel-auth' do
        source 'sentinel-auth.conf.ctmpl.erb'
        cookbook 'redis'
        destination '/run/rb-secrets/redis-sentinel/auth.conf'
        owner 'root'
        group group # the unit's wait-for-file step runs as redis
        mode '0640'
        unit 'redis-sentinel'
        action :add
      end

      execute 'selinux-redis-sentinel-run' do
        command "semanage fcontext -a -t redis_var_run_t '/var/run/redis-sentinel(/.*)?'"
        not_if "semanage fcontext -l -C | grep -qF '/var/run/redis-sentinel(/.*)?'"
      end

      directory '/etc/systemd/system/redis-sentinel.service.d' do
        mode '0755'
      end

      # 60-: after the 50-openbao-* drop-in that waits for the auth file
      file '/etc/systemd/system/redis-sentinel.service.d/60-openbao-run.conf' do
        content <<~UNIT
          # Generated by chef (cookbook-redis)
          [Service]
          RuntimeDirectory=redis-sentinel
          # Sentinel's rewrites would create the file 0644
          RuntimeDirectoryMode=0700
          UMask=0077
          RuntimeDirectoryPreserve=yes
          ExecStartPre=+/bin/sh -c 'c=#{sentinel_run}/sentinel.conf; [ -s $$c ] || cp #{redis_dir}/sentinel.conf $$c; grep -v "^sentinel auth-pass " $$c > $$c.new; cat /run/rb-secrets/redis-sentinel/auth.conf >> $$c.new; echo >> $$c.new; chown #{user}:#{group} $$c.new; chmod 0600 $$c.new; mv -f $$c.new $$c'
          ExecStart=
          ExecStart=/usr/bin/redis-sentinel #{sentinel_run}/sentinel.conf --daemonize no --supervised systemd
        UNIT
        mode '0644'
        action :create
        notifies :run, 'execute[systemctl-daemon-reload-redis-sentinel]', :immediately
        notifies :restart, 'service[redis-sentinel]', :delayed
      end

      execute 'systemctl-daemon-reload-redis-sentinel' do
        command 'systemctl daemon-reload'
        action :nothing
      end

      service 'redis-sentinel' do
        service_name 'redis-sentinel'
        ignore_failure true
        supports status: true, restart: true, enable: true
        action [:start, :enable]
      end
    else
      service 'redis-sentinel' do
        service_name 'redis-sentinel'
        ignore_failure true
        supports status: true, enable: true
        action [:stop, :disable]
      end
    end

    Chef::Log.info('Redis cookbook has been processed')
  rescue => e
    Chef::Log.error(e.message)
  end
end

action :remove do
  begin
    redis_dir = new_resource.redis_dir
    data_dir = new_resource.data_dir
    log_file = new_resource.log_file
    pid_file = new_resource.pid_file
    sentinel_data_dir = new_resource.sentinel_data_dir
    sentinel_log_file = new_resource.sentinel_log_file
    sentinel_pid_file = new_resource.sentinel_pid_file

    service 'redis' do
      service_name 'redis'
      ignore_failure true
      supports status: true, enable: true
      action [:stop, :disable]
    end

    directory data_dir do
      recursive true
      action :delete
      ignore_failure true
    end

    directory redis_dir do
      recursive true
      action :delete
      ignore_failure true
    end

    file log_file do
      action :delete
      ignore_failure true
    end

    file pid_file do
      action :delete
      ignore_failure true
    end

    service 'redis-sentinel' do
      service_name 'redis-sentinel'
      ignore_failure true
      supports status: true, enable: true
      action [:stop, :disable]
    end

    directory sentinel_data_dir do
      recursive true
      action :delete
      ignore_failure true
    end

    file sentinel_log_file do
      action :delete
      ignore_failure true
    end

    file sentinel_pid_file do
      action :delete
      ignore_failure true
    end

    Chef::Log.info('Redis service has been removed')
  rescue => e
    Chef::Log.error(e.message)
  end
end

action :register do
  begin
    unless node['redis']['registered']
      query = {}
      query['ID'] = "redis-#{node['hostname']}"
      query['Name'] = 'redis'
      query['Address'] = node['ipaddress_sync']
      query['Port'] = node['redis']['port']
      json_query = Chef::JSONCompat.to_json(query)

      execute 'Register service in consul' do
        command "curl -X PUT http://localhost:8500/v1/agent/service/register -d '#{json_query}' &>/dev/null"
        action :nothing
      end.run_action(:run)

      node.normal['redis']['registered'] = true
    end
    Chef::Log.info('Redis service has been registered in consul')
  rescue => e
    Chef::Log.error(e.message)
  end
end

action :deregister do
  begin
    if node['redis']['registered']
      execute 'Deregister service in consul' do
        command "curl -X PUT http://localhost:8500/v1/agent/service/deregister/redis-#{node['hostname']} &>/dev/null"
        action :nothing
      end.run_action(:run)

      node.normal['redis']['registered'] = false
    end
    Chef::Log.info('Redis service has been deregistered from consul')
  rescue => e
    Chef::Log.error(e.message)
  end
end
